// Builds defaults.js from tools/checklists.txt.  Run: node tools/build_defaults.js
// Bump DEFAULTS_VERSION below whenever the checklist text changes, and add the previous version's signature
// (printed by this script) to KNOWN_SIGS in index.html, so devices with unedited checklists update automatically.
'use strict';
const fs = require('fs'), path = require('path');
const DEFAULTS_VERSION = 2;
const COLORS = { 'Preflight': '#4a4f57', 'Start & Taxi': '#1e5bd8', 'Flight': '#138a4a', 'After Landing': '#6b3fc7', 'Emergency': '#c62828' };
const src = fs.readFileSync(path.join(__dirname, 'checklists.txt'), 'utf8').split('\n');
const out = []; let cur = null;
src.forEach((line, i) => {
  const m = /^=== (.+?) \| (.+)$/.exec(line);
  if (m) { cur = { title: m[1].trim(), group: m[2].trim(), lines: [] }; out.push(cur); return; }
  if (!cur) return;   // header comments
  cur.lines.push(line.replace(/\s+$/, ''));
});
const D = out.map(c => {
  const root = c.group.split('/')[0], color = COLORS[root];
  if (!color) throw new Error('unknown group ' + c.group);
  while (c.lines.length && !c.lines[c.lines.length - 1]) c.lines.pop();
  if (c.lines.some(l => /^=== /.test(l))) throw new Error('bad header in ' + c.title);
  return { title: c.title, group: c.group, color: color, text: c.lines.join('\n') };
});
const titles = new Set();
D.forEach(d => { if (titles.has(d.title)) throw new Error('duplicate title ' + d.title); titles.add(d.title); });
// every @EMERGENCY target and -> button target must exist
const norm = t => t.toLowerCase().replace(/\s+/g, ' ').trim();
const groupsSeen = new Set(D.map(d => norm(d.group)).concat(D.map(d => norm(d.group.split('/').pop()))));
D.forEach(d => d.text.split('\n').forEach(l => {
  let m = /^@EMERGENCY (.+)$/.exec(l);
  if (m && !titles.has(m[1].trim()) && !groupsSeen.has(norm(m[1]))) throw new Error(d.title + ': emergency target not found: ' + m[1]);
  m = /^-> .* : (.+)$/.exec(l);
  if (m && !titles.has(m[1].trim())) throw new Error(d.title + ': button target not found: ' + m[1]);
}));
const js = '// N523LT DA40 XLS default checklists. Generated by tools/build_defaults.js from tools/checklists.txt; do not edit.\n'
  + '// Source rule: Emergency Checklist Card 2026 11 10 is primary; DA 40 AFM Doc. 6.01.01-E Rev 10 and G1000/GFC 700 AFMS 190-00492-10 Rev 8 fill gaps.\n'
  + 'const DEFAULTS_VERSION = ' + DEFAULTS_VERSION + ';\nconst DEFAULTS = ' + JSON.stringify(D, null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'defaults.js'), js);
console.log('defaults.js: v' + DEFAULTS_VERSION + ', ' + D.length + ' checklists');
